// AI contribution: 50% or more AI-generated
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import openapiTS from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const { values } = parseArgs({
  options: {
    check: { type: "boolean", default: false },
    output: { type: "string" },
  },
});

const defaultOutput = fileURLToPath(new URL("../src/shared/api/generated.d.ts", import.meta.url));
const outputPath = values.output ? resolve(values.output) : defaultOutput;

// Generate the schema using the existing Python environment without starting Django.
const schema = execFileSync(
  "uv",
  [
    "run",
    "--no-cache",
    "--no-sync",
    "--no-python-downloads",
    "python",
    "manage.py",
    "spectacular",
    "--format",
    "openapi-json",
    "--validate",
    "--fail-on-warn",
  ],
  {
    cwd: new URL("../../backend/", import.meta.url),
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  },
);

const types = await openapiTS(JSON.parse(schema), { alphabetize: true, commentHeader: "" });
const generated = await format("// Generated by pnpm gen:api. Do not edit by hand.\n\n" + types, {
  ...(await resolveConfig(defaultOutput)),
  parser: "typescript",
  endOfLine: "lf",
});

if (values.check) {
  let existing;
  try {
    existing = await readFile(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  // Git may check out CRLF on Windows; compare the generated content consistently.
  if (existing?.replaceAll("\r\n", "\n") !== generated) {
    console.error("API types are missing or outdated. Run pnpm gen:api and commit the result.");
    process.exitCode = 1;
  } else {
    console.log("API types are up to date.");
  }
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Generated API types: ${outputPath}`);
}
