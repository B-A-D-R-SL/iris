// AI contribution: 50% or more AI-generated
import { execFileSync } from "node:child_process";
import { lstat, readFile, realpath, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { text } from "node:stream/consumers";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import openapiTS from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const { values } = parseArgs({
  options: {
    check: { type: "boolean", default: false },
    "schema-stdin": { type: "boolean", default: false },
    "temporary-output": { type: "boolean", default: false },
  },
});

const defaultOutput = fileURLToPath(new URL("../src/shared/api/generated.d.ts", import.meta.url));
let outputPath = defaultOutput;

// Tests may use one fixed filename in a private mkdtemp directory, never a CLI path.
if (values["temporary-output"]) {
  const directory = await realpath(process.cwd());
  const info = await lstat(directory);
  if (
    dirname(directory) !== (await realpath(tmpdir())) ||
    !/^iris-api-generation-[A-Za-z0-9]{6}$/.test(basename(directory)) ||
    (typeof process.getuid === "function" &&
      (info.uid !== process.getuid() || (info.mode & 0o077) !== 0))
  ) {
    throw new Error(
      "Temporary output requires a private iris-api-generation-* directory in tmpdir.",
    );
  }
  outputPath = join(directory, "generated.d.ts");
}

try {
  const info = await lstat(outputPath);
  if (!info.isFile() || info.nlink !== 1) {
    throw new Error("API output must be a regular file without symbolic or hard links.");
  }
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}

const pythonExecutable = fileURLToPath(
  new URL(
    process.platform === "win32"
      ? "../../backend/.venv/Scripts/python.exe"
      : "../../backend/.venv/bin/python",
    import.meta.url,
  ),
);

// Use the installed interpreter directly: no PATH lookup, dependency sync, or server.
const schema = values["schema-stdin"]
  ? await text(process.stdin)
  : execFileSync(
      pythonExecutable,
      [
        "-B",
        "manage.py",
        "spectacular",
        "--format",
        "openapi-json",
        "--validate",
        "--fail-on-warn",
      ],
      {
        cwd: new URL("../../backend/", import.meta.url),
        encoding: "utf8",
        env: { ...process.env, PYTHONUTF8: "1", PYTHONIOENCODING: "utf-8" },
        maxBuffer: Infinity,
        stdio: ["ignore", "pipe", "inherit"],
      },
    );

const types = await openapiTS(JSON.parse(schema), { alphabetize: true, commentHeader: "" });
const generated = await format("// Generated by pnpm gen:api. Do not edit by hand.\n\n" + types, {
  ...(await resolveConfig(defaultOutput)),
  parser: "typescript",
  endOfLine: "lf",
});

if (values.check) {
  let existing;
  try {
    existing = await readFile(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  // Git may check out CRLF on Windows; compare the generated content consistently.
  if (existing?.replaceAll("\r\n", "\n") !== generated) {
    console.error("API types are missing or outdated. Run pnpm gen:api and commit the result.");
    process.exitCode = 1;
  } else {
    console.log("API types are up to date.");
  }
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Generated API types: ${outputPath}`);
}
